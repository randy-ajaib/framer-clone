import { nodeCss } from './css';
import { isFrame } from './tree';
import type { Asset, Document, Node, NodeId } from './types';

export interface ExportOptions {
  /** 'files' writes images/ and fonts/ paths for the zip; 'inline' embeds images and points fonts at fontBase. */
  mode: 'files' | 'inline';
  /** Where the Lato .ttf files live when mode is 'inline' (an absolute URL ending in /fonts/). */
  fontBase?: string;
}

export interface ExportResult {
  html: string;
  css: string;
  /** Images to write next to index.html, keyed by their path in the zip. */
  images: Record<string, Asset>;
  /** Lato weights used, so the zip can include only those files. */
  fontFiles: string[];
}

const latoFiles: Record<number, string> = { 400: 'Lato-Regular.ttf', 600: 'Lato-SemiBold.ttf', 700: 'Lato-Bold.ttf' };

export function slugify(name: string): string {
  const s = name
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return /^[a-z]/.test(s) ? s : `n-${s || 'node'}`;
}

export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const extFor = (mime: string) =>
  ({ 'image/png': 'png', 'image/jpeg': 'jpg', 'image/gif': 'gif', 'image/webp': 'webp', 'image/svg+xml': 'svg' })[
    mime
  ] ?? 'bin';

/** Turns the document into a standalone page. Pure: no DOM, no network. */
export function exportSite(doc: Document, opts: ExportOptions): ExportResult {
  const classOf = new Map<NodeId, string>();
  const used = new Map<string, number>();
  const visible = (id: NodeId) => !doc.nodes[id].hidden;

  const assign = (id: NodeId) => {
    const node = doc.nodes[id];
    const base = slugify(node.name);
    const count = used.get(base) ?? 0;
    used.set(base, count + 1);
    classOf.set(id, count === 0 ? base : `${base}-${count + 1}`);
    if (isFrame(node)) node.children.filter(visible).forEach(assign);
  };
  assign(doc.rootId);

  const images: Record<string, Asset> = {};
  const imagePath = new Map<string, string>();
  const srcFor = (assetId: string): string | null => {
    const asset = doc.assets[assetId];
    if (!asset) return null;
    if (opts.mode === 'inline') return asset.dataUrl;
    if (!imagePath.has(assetId)) {
      const path = `images/${slugify(asset.name.replace(/\.[a-z0-9]+$/i, ''))}.${extFor(asset.mime)}`;
      imagePath.set(assetId, path);
      images[path] = asset;
    }
    return imagePath.get(assetId)!;
  };

  const weights = new Set<number>();
  const render = (id: NodeId, depth: number): string => {
    const node: Node = doc.nodes[id];
    const pad = '  '.repeat(depth);
    const cls = classOf.get(id)!;
    switch (node.type) {
      case 'frame': {
        const kids = node.children.filter(visible).map((c) => render(c, depth + 1));
        if (kids.length === 0) return `${pad}<div class="${cls}"></div>`;
        return `${pad}<div class="${cls}">\n${kids.join('\n')}\n${pad}</div>`;
      }
      case 'text':
        if (node.font.family === 'Lato') weights.add(node.font.weight);
        return `${pad}<${node.tag} class="${cls}">${escapeHtml(node.text)}</${node.tag}>`;
      case 'image': {
        const src = node.assetId ? srcFor(node.assetId) : null;
        if (!src) return `${pad}<div class="${cls} placeholder" role="img" aria-label="${escapeHtml(node.alt)}"></div>`;
        return `${pad}<img class="${cls}" src="${escapeHtml(src)}" alt="${escapeHtml(node.alt)}" loading="lazy">`;
      }
      case 'rect':
        return `${pad}<div class="${cls}"></div>`;
    }
  };
  const body = render(doc.rootId, 2);

  const rules: string[] = [];
  for (const [id, cls] of classOf) {
    const node = doc.nodes[id];
    const decls = nodeCss(node, node.parentId ? doc.nodes[node.parentId] : null);
    if (id === doc.rootId) decls.push(['min-height', '100vh']);
    if (decls.length === 0) continue;
    rules.push(`.${cls} {\n${decls.map(([p, v]) => `  ${p}: ${v};`).join('\n')}\n}`);
  }

  const fontBase = opts.mode === 'files' ? 'fonts/' : (opts.fontBase ?? 'fonts/');
  const fontFiles = [...weights].sort().map((w) => latoFiles[w]);
  const fontFaces = [...weights]
    .sort()
    .map(
      (w) =>
        `@font-face {\n  font-family: 'Lato';\n  font-weight: ${w};\n  font-style: normal;\n  font-display: swap;\n  src: url('${fontBase}${latoFiles[w]}') format('truetype');\n}`,
    );

  const css = [
    '/* Generated by Site Builder */',
    ...fontFaces,
    '*, *::before, *::after { box-sizing: border-box; }',
    'html, body { margin: 0; }',
    "body { font-family: 'Lato', 'Helvetica Neue', Arial, sans-serif; -webkit-font-smoothing: antialiased; }",
    'img { max-width: 100%; }',
    '.placeholder { background: #e6e8ee; }',
    ...rules,
  ].join('\n\n');

  const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>${escapeHtml(doc.title)}</title>
    <link rel="stylesheet" href="styles.css">
  </head>
  <body>
${body}
  </body>
</html>
`;
  return { html, css: css + '\n', images, fontFiles };
}

/** The same page as one HTML string, for the preview iframe. */
export function exportInlinePage(doc: Document, fontBase: string): string {
  const { html, css } = exportSite(doc, { mode: 'inline', fontBase });
  return html.replace('<link rel="stylesheet" href="styles.css">', `<style>\n${css}</style>`);
}

function dataUrlToBytes(dataUrl: string): Uint8Array {
  const [meta, data] = dataUrl.split(',', 2);
  if (meta.endsWith(';base64')) {
    const bin = atob(data);
    return Uint8Array.from(bin, (c) => c.charCodeAt(0));
  }
  return new TextEncoder().encode(decodeURIComponent(data));
}

/** Builds site.zip in the browser. `fontBase` is the URL folder holding the Lato .ttf files. */
export async function buildZip(doc: Document, fontBase: string): Promise<Blob> {
  const { default: JSZip } = await import('jszip');
  const { html, css, images, fontFiles } = exportSite(doc, { mode: 'files' });
  const zip = new JSZip();
  zip.file('index.html', html);
  zip.file('styles.css', css);
  for (const [path, asset] of Object.entries(images)) zip.file(path, dataUrlToBytes(asset.dataUrl));
  for (const file of fontFiles) {
    const res = await fetch(`${fontBase}${file}`);
    if (res.ok) zip.file(`fonts/${file}`, await res.arrayBuffer());
  }
  return zip.generateAsync({ type: 'blob' });
}
